const db = require('../config/database');
const { getPagination, getTotalPages } = require('../utils/helpers');

class QuoteService {
  // Get all quotes with pagination
  async getAllQuotes(page = 1, limit = 20, language = 'en') {
    const { offset } = getPagination(page, limit);

    const countResult = await db.query(
      'SELECT COUNT(*) FROM quotes WHERE language = $1',
      [language]
    );
    const totalCount = parseInt(countResult.rows[0].count);

    const result = await db.query(
      `SELECT id, text, author, category, language, created_at 
       FROM quotes 
       WHERE language = $1 
       ORDER BY created_at DESC 
       LIMIT $2 OFFSET $3`,
      [language, limit, offset]
    );

    return {
      quotes: result.rows,
      pagination: {
        page,
        limit,
        total: totalCount,
        totalPages: getTotalPages(totalCount, limit),
      },
    };
  }

  // Get or create initial personalized quotes
  // Safe to call on login, registration, or sync - returns existing quotes or creates new ones
  async getInitialPersonalizedQuotes(userId, language = 'en') {
    // Get user's language preference
    const userResult = await db.query(
      'SELECT motivation, language FROM users WHERE id = $1',
      [userId]
    );

    if (userResult.rows.length === 0) {
      throw new Error('User not found');
    }

    const user = userResult.rows[0];
    const userLanguage = language || user.language || 'en';

    // Check if user already has personalized quotes
    const existingQuotesResult = await db.query(
      `SELECT 
        q.id,
        q.text,
        q.author,
        q.category,
        q.language,
        uq.is_favorite,
        uq.is_ai_generated,
        q.ai_generation_status,
        uq.created_at as linked_at
       FROM user_quotes uq
       JOIN quotes q ON q.id = uq.quote_id
       WHERE uq.user_id = $1
       ORDER BY uq.created_at DESC`,
      [userId]
    );

    // If user already has quotes, return them
    if (existingQuotesResult.rows.length > 0) {
      return {
        success: true,
        message: 'Personalized quotes retrieved successfully',
        quotes: existingQuotesResult.rows,
        count: existingQuotesResult.rows.length,
        alreadyInitialized: true,
      };
    }

    // No existing quotes, create new ones
    // Get 7 random quotes from existing default quotes
    const quotesResult = await db.query(
      `SELECT id, text, author, category, language
       FROM quotes
       WHERE is_default = true AND language = $1
       ORDER BY RANDOM()
       LIMIT 7`,
      [userLanguage]
    );

    if (quotesResult.rows.length === 0) {
      throw new Error('No default quotes available for initialization');
    }

    // Link these quotes to the user (mark as personalized but not AI-generated)
    const insertPromises = quotesResult.rows.map((quote) =>
      db.query(
        `INSERT INTO user_quotes (user_id, quote_id, is_ai_generated, is_favorite)
         VALUES ($1, $2, false, false)
         ON CONFLICT (user_id, quote_id) DO NOTHING
         RETURNING created_at as linked_at`,
        [userId, quote.id]
      )
    );

    await Promise.all(insertPromises);

    // Add metadata to quotes
    const quotesWithMetadata = quotesResult.rows.map(quote => ({
      ...quote,
      is_favorite: false,
      is_ai_generated: false,
    }));

    return {
      success: true,
      message: 'Initial personalized quotes created successfully',
      quotes: quotesWithMetadata,
      count: quotesWithMetadata.length,
      alreadyInitialized: false,
    };
  }

  // Get random quote
  async getRandomQuote(userId = null, language = 'en') {
    let query;
    let params;

    if (userId) {
      // Get random quote for authenticated user with personalized information
      // This query does the following:
      // 1. Selects all quote fields (id, text, author, category, language)
      // 2. Adds two computed boolean fields:
      //    - is_favorite: true if user has marked this quote as favorite
      //    - is_ai_generated: true if this quote was generated by AI for this user
      // 3. Uses LEFT JOIN to include all quotes, even if user hasn't interacted with them
      // 4. BOOL_OR() aggregate function returns true if ANY matching user_quote has the flag set
      //    (handles cases where there might be duplicate entries, though should be prevented by UNIQUE constraint)
      // 5. COALESCE(..., false) ensures we return false instead of NULL when no user_quote exists
      // 6. GROUP BY is required because we're using aggregate functions (BOOL_OR)
      //    - Must include all non-aggregated columns from SELECT
      // 7. ORDER BY RANDOM() picks a random quote from all available quotes
      // 8. Filters by language to match user's preference
      query = `
        SELECT q.id, q.text, q.author, q.category, q.language, 
               COALESCE(BOOL_OR(uq.is_favorite), false) as is_favorite,
               COALESCE(BOOL_OR(uq.is_ai_generated), false) as is_ai_generated
        FROM quotes q
        LEFT JOIN user_quotes uq ON q.id = uq.quote_id AND uq.user_id = $1
        WHERE q.language = $2
        GROUP BY q.id, q.text, q.author, q.category, q.language
        ORDER BY RANDOM()
        LIMIT 1
      `;
      params = [userId, language];
    } else {
      // Get random default quote for unauthenticated users
      // Simple query that:
      // 1. Only returns pre-loaded default quotes (is_default = true)
      // 2. Filters by language
      // 3. Picks a random quote
      // No personalization since there's no user context
      query = `
        SELECT id, text, author, category, language
        FROM quotes
        WHERE is_default = true AND language = $1
        ORDER BY RANDOM()
        LIMIT 1
      `;
      params = [language];
    }

    const result = await db.query(query, params);
    return result.rows[0] || null;
  }

  // Get user's favorite quotes
  async getFavoriteQuotes(userId, page = 1, limit = 20) {
    const { offset } = getPagination(page, limit);

    const countResult = await db.query(
      'SELECT COUNT(*) FROM user_quotes WHERE user_id = $1 AND is_favorite = true',
      [userId]
    );
    const totalCount = parseInt(countResult.rows[0].count);

    const result = await db.query(
      `SELECT q.id, q.text, q.author, q.category, q.language, 
              uq.is_ai_generated, uq.created_at as added_at
       FROM quotes q
       JOIN user_quotes uq ON q.id = uq.quote_id
       WHERE uq.user_id = $1 AND uq.is_favorite = true
       ORDER BY uq.created_at DESC
       LIMIT $2 OFFSET $3`,
      [userId, limit, offset]
    );

    return {
      quotes: result.rows,
      pagination: {
        page,
        limit,
        total: totalCount,
        totalPages: getTotalPages(totalCount, limit),
      },
    };
  }

  // Toggle favorite status
  async toggleFavorite(userId, quoteId) {
    // Check if quote exists
    const quoteExists = await db.query(
      'SELECT id FROM quotes WHERE id = $1',
      [quoteId]
    );

    if (quoteExists.rows.length === 0) {
      throw new Error('Quote not found');
    }

    // Check if user_quote relation exists
    const existingRelation = await db.query(
      'SELECT is_favorite FROM user_quotes WHERE user_id = $1 AND quote_id = $2',
      [userId, quoteId]
    );

    let isFavorite;

    if (existingRelation.rows.length === 0) {
      // Create new relation with favorite = true
      await db.query(
        'INSERT INTO user_quotes (user_id, quote_id, is_favorite) VALUES ($1, $2, true)',
        [userId, quoteId]
      );
      isFavorite = true;
    } else {
      // Toggle existing favorite status
      isFavorite = !existingRelation.rows[0].is_favorite;
      await db.query(
        'UPDATE user_quotes SET is_favorite = $1 WHERE user_id = $2 AND quote_id = $3',
        [isFavorite, userId, quoteId]
      );
    }

    return { isFavorite };
  }

  // Create custom quote
  async createCustomQuote(userId, text, author = null, category = 'motivation', language = 'en', is_ai_generated = false) {
    if (is_ai_generated) {
      // AI quote - create placeholder in quotes table with pending status
      const tomorrow = new Date();
      tomorrow.setDate(tomorrow.getDate() + 1);
      tomorrow.setHours(0, 0, 0, 0);

      // Create quote entry with NULL text (to be generated)
      const quoteResult = await db.query(
        `INSERT INTO quotes 
         (text, author, category, is_default, language, ai_generation_status, ai_generate_on) 
         VALUES (NULL, $1, $2, false, $3, 'pending', $4) 
         RETURNING id, text, author, category, language, ai_generation_status, created_at`,
        [author, category, language, tomorrow]
      );

      const quote = quoteResult.rows[0];

      // Link to user with AI flag
      await db.query(
        'INSERT INTO user_quotes (user_id, quote_id, is_ai_generated) VALUES ($1, $2, true)',
        [userId, quote.id]
      );

      return {
        id: quote.id,
        text: null,
        author: quote.author,
        category: quote.category,
        language: quote.language,
        is_ai_generated: true,
        ai_generation_status: 'pending',
        created_at: quote.created_at,
      };
    } else {
      // Regular custom quote - create global quote and link to user
      const quoteResult = await db.query(
        'INSERT INTO quotes (text, author, category, is_default, language) VALUES ($1, $2, $3, false, $4) RETURNING *',
        [text, author, category, language]
      );

      const quote = quoteResult.rows[0];

      // Link to user
      await db.query(
        'INSERT INTO user_quotes (user_id, quote_id, is_ai_generated) VALUES ($1, $2, false)',
        [userId, quote.id]
      );

      return quote;
    }
  }

  // Delete user's custom quote
  async deleteCustomQuote(userId, quoteId) {
    // Verify quote belongs to user and is not a default quote
    const result = await db.query(
      `SELECT q.id, q.is_default 
       FROM quotes q
       JOIN user_quotes uq ON q.id = uq.quote_id
       WHERE q.id = $1 AND uq.user_id = $2`,
      [quoteId, userId]
    );

    if (result.rows.length === 0) {
      throw new Error('Quote not found');
    }

    if (result.rows[0].is_default) {
      throw new Error('Cannot delete default quotes');
    }

    // Delete quote (CASCADE will handle user_quotes)
    await db.query('DELETE FROM quotes WHERE id = $1', [quoteId]);

    return true;
  }

  // Get quotes by category
  async getQuotesByCategory(category, language = 'en', limit = 10) {
    const result = await db.query(
      `SELECT id, text, author, category, language 
       FROM quotes 
       WHERE category = $1 AND language = $2 
       ORDER BY RANDOM() 
       LIMIT $3`,
      [category, language, limit]
    );

    return result.rows;
  }

  // Search quotes
  async searchQuotes(searchTerm, language = 'en', limit = 20) {
    const result = await db.query(
      `SELECT id, text, author, category, language 
       FROM quotes 
       WHERE (text ILIKE $1 OR author ILIKE $1 OR category ILIKE $1) 
       AND language = $2 
       LIMIT $3`,
      [`%${searchTerm}%`, language, limit]
    );

    return result.rows;
  }
}

module.exports = new QuoteService();

