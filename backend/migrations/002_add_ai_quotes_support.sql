-- Add AI quote support to user_quotes table
ALTER TABLE user_quotes 
ADD COLUMN IF NOT EXISTS text TEXT,
ADD COLUMN IF NOT EXISTS author VARCHAR(255),
ADD COLUMN IF NOT EXISTS category VARCHAR(100) DEFAULT 'motivation',
ADD COLUMN IF NOT EXISTS ai_generation_status VARCHAR(20) DEFAULT 'pending',
ADD COLUMN IF NOT EXISTS ai_generate_on DATE,
ADD COLUMN IF NOT EXISTS ai_generated_at TIMESTAMP,
ADD COLUMN IF NOT EXISTS ai_error_message TEXT;

-- Add index for night job query
CREATE INDEX IF NOT EXISTS idx_ai_pending ON user_quotes(is_ai_generated, ai_generation_status, ai_generate_on)
WHERE is_ai_generated = true;

-- Add comment for clarity
COMMENT ON COLUMN user_quotes.text IS 'User-created quote text or AI-generated text';
COMMENT ON COLUMN user_quotes.is_ai_generated IS 'True if this quote should be/was generated by AI';
COMMENT ON COLUMN user_quotes.ai_generation_status IS 'Status: pending, processing, completed, failed';
COMMENT ON COLUMN user_quotes.ai_generate_on IS 'Date when AI should generate this quote (usually tomorrow)';
COMMENT ON COLUMN user_quotes.ai_generated_at IS 'Timestamp when AI completed generation';
